import test from 'node:test';
import assert from 'node:assert/strict';
import { nextRun } from '../src/cron.js';

for (const [expr, after, want] of [
  ["* * * * *", "2026-03-10T10:00:00Z", "2026-03-10T10:01:00.000Z"],
  ["*/15 * * * *", "2026-03-10T10:07:00Z", "2026-03-10T10:15:00.000Z"],
  ["30 9 * * *", "2026-03-10T10:00:00Z", "2026-03-11T09:30:00.000Z"],
  ["0 0 1 * *", "2026-03-10T10:00:00Z", "2026-04-01T00:00:00.000Z"],
  ["0 9 * * 1-5", "2026-03-14T12:00:00Z", "2026-03-16T09:00:00.000Z"],
  ["0,30 8-10 * * *", "2026-03-10T09:45:00Z", "2026-03-10T10:00:00.000Z"],
  ["0 0 29 2 *", "2026-03-01T00:00:00Z", "2028-02-29T00:00:00.000Z"],
  ["5 4 * * 7", "2026-03-10T00:00:00Z", "2026-03-15T04:05:00.000Z"],
  ["0 12 */10 * *", "2026-03-11T00:00:00Z", "2026-03-11T12:00:00.000Z"],
  ["0 0 13 * 5", "2026-03-01T00:00:00Z", "2026-03-06T00:00:00.000Z"],
  ["59 23 31 12 *", "2026-12-31T23:59:00Z", "2027-12-31T23:59:00.000Z"],
  ["10-20/5 * * * *", "2026-03-10T10:21:00Z", "2026-03-10T11:10:00.000Z"],
  ["0 0 * 6 *", "2026-03-10T10:00:00Z", "2026-06-01T00:00:00.000Z"],
  ["*/20 */6 * * *", "2026-03-10T05:50:30Z", "2026-03-10T06:00:00.000Z"],
]) test(`visible ${JSON.stringify(expr)} after ${after}`, () => {
  const got = nextRun(expr, new Date(after));
  assert.equal(got === null ? null : got.toISOString(), want);
});

for (const expr of ["","* * * *","61 * * * *","* 24 * * *","*/0 * * * *","5-1 * * * *","a b c d e","* * 0 * *","* * * 13 *","* * * * 8"]) test(`rejects ${JSON.stringify(expr)}`, () => assert.throws(() => nextRun(expr, new Date('2026-01-01T00:00:00Z')), { name: 'SyntaxError' }));
