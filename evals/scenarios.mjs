#!/usr/bin/env node
// Task scenario eval. Two modes:
//   node evals/scenarios.mjs --check [--scenario id,id]      FREE, offline, runs in CI: proves every scenario's graders fail on the bare
//                                                              fixture and pass on its reference solution/ overlay.
//   node evals/scenarios.mjs --dry-run | (run)                PAID: runs `claude -p` per scenario and arm, then grades with the same graders.
// Paid options: [--scenario id,id] [--arms baseline,skills] [--runs N] [--model sonnet] [--budget USD per run, default 1.0]
//               [--max-runs N, default 20] [--out evals/results/FILE.json] [--keep]
// Arms: baseline = the fixture only; skills = the fixture plus the project generated by init.mjs for the scenario's type/stack/domains.
// Set CLAUDE_BIN if `claude` is not on PATH. The paid mode has not been run by the author yet (no measured results exist).
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { listScenarios, loadScenario, checkScenario, prepare, grade, categoryRates } from './scenario-lib.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const INIT = path.join(HERE, '..', 'init.mjs');
const args = process.argv.slice(2);
const opt = (n, d) => { const i = args.indexOf(n); return i >= 0 && args[i + 1] ? args[i + 1] : d; };
const has = (n) => args.includes(n);
const ids = (opt('--scenario', '') ? opt('--scenario', '').split(',') : listScenarios());
const scenarios = ids.map((id) => loadScenario(id));

if (has('--check')) {
  let bad = 0;
  for (const s of scenarios) {
    const problems = checkScenario(s);
    bad += problems.length;
    console.log(`  ${problems.length ? '✖' : '✔'} ${s.id}: ${s.graders.length} graders${problems.length ? '\n      ' + problems.join('\n      ') : ''}`);
  }
  console.log(bad ? `${bad} problem(s)` : `${scenarios.length} scenario(s) valid`);
  process.exit(bad ? 1 : 0);
}

const arms = opt('--arms', 'baseline,skills').split(',');
const runs = Math.max(1, Number(opt('--runs', '1')) || 1);
const model = opt('--model', 'sonnet');
const budget = Number(opt('--budget', '1.0'));
const maxRuns = Number(opt('--max-runs', '20'));
const total = scenarios.length * arms.length * runs;
const BIN = process.env.CLAUDE_BIN || 'claude';
console.log(`${total} runs = ${scenarios.length} scenarios x ${arms.length} arms x ${runs}, model ${model}, cap $${budget}/run (worst case $${(total * budget).toFixed(2)}).`);
if (has('--dry-run')) { for (const s of scenarios) console.log(`  ${s.id}: ${s.title}`); console.log('--dry-run: nothing executed.'); process.exit(0); }
if (total > maxRuns) { console.error(`${total} runs exceed --max-runs ${maxRuns}. Raise it deliberately or narrow --scenario/--runs.`); process.exit(2); }

const results = [];
for (let r = 0; r < runs; r++) {
  for (const s of scenarios) {
    for (const arm of arms) {
      const work = prepare(s, arm, INIT);
      const cli = ['-p', s.prompt, '--output-format', 'json', '--model', model, '--setting-sources', 'project', '--strict-mcp-config', '--no-session-persistence',
        '--max-budget-usd', String(budget), '--permission-mode', 'acceptEdits', '--allowed-tools', 'Read', 'Grep', 'Glob', 'Edit', 'Write'];
      const p = spawnSync(BIN, cli, { cwd: work, encoding: 'utf8', timeout: 600000 });
      let j; try { j = JSON.parse(p.stdout); } catch { j = { error: (p.stderr || p.stdout || 'no output').slice(0, 300) }; }
      if (j.error || j.is_error) { console.error(`  ${s.id} ${arm} run ${r + 1}: FAILED ${j.error || j.result}`); continue; }
      const graders = grade(work, s);
      const pass = graders.every((g) => g.pass);
      results.push({ scenario: s.id, arm, run: r + 1, pass, cost: j.total_cost_usd ?? 0, turns: j.num_turns ?? 0, graders });
      console.log(`  ${pass ? '✔' : '✖'} ${s.id.padEnd(28)} ${arm.padEnd(8)} $${(j.total_cost_usd ?? 0).toFixed(3)} ${j.num_turns ?? 0} turns  ${graders.filter((g) => !g.pass).map((g) => g.id).join(', ')}`);
      if (!has('--keep')) fs.rmSync(work, { recursive: true, force: true });
    }
  }
}
for (const c of categoryRates(results)) console.log(`  ${c.arm.padEnd(8)} ${c.category.padEnd(13)} ${c.pass}/${c.total}`);
if (opt('--out', '')) {
  fs.mkdirSync(path.dirname(path.resolve(opt('--out', ''))), { recursive: true });
  fs.writeFileSync(opt('--out', ''), JSON.stringify({ kind: 'scenarios', date: new Date().toISOString().slice(0, 10), model, runsPerCell: runs, budgetPerRunUsd: budget, runs: results }, null, 2) + '\n');
  console.log(`results written to ${opt('--out', '')}`);
}
