#!/usr/bin/env node
// Builds evals/REPORT.md from evals/results/*.json (written by evals/live.mjs --out and evals/scenarios.mjs --out).
// node evals/report.mjs [--results DIR] [--out FILE]   Offline and free. With no results it says the skills are unevaluated.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const pct = (n, d) => (d ? `${Math.round((100 * n) / d)}%` : 'n/a');
// 95% Wilson score interval: a pass rate from few calls is shown with its uncertainty.
const wilson = (k, n) => { if (!n) return ''; const z = 1.96, p = k / n, den = 1 + z * z / n, c = p + z * z / (2 * n), m = z * Math.sqrt((p * (1 - p) + z * z / (4 * n)) / n); return `${Math.round(100 * (c - m) / den)}-${Math.round(100 * (c + m) / den)}%`; };

export function buildReport(results) {
  const trig = results.filter((r) => r.kind === 'trigger');
  const scen = results.filter((r) => r.kind === 'scenarios');
  const L = ['# Evaluation report', '', 'Generated by `node evals/report.mjs` from `evals/results/*.json`. Numbers come only from recorded runs; nothing here is estimated.', ''];
  if (!trig.length && !scen.length) {
    L.push('**No live results recorded yet. The skills are unevaluated.** The offline checks (`node evals/run.mjs`, `node evals/scenarios.mjs --check`, `node test.mjs`) guard description quality and grader validity; they do not measure model behavior.', '');
    return L.join('\n');
  }
  if (trig.length) {
    L.push('## Skill triggering (live model, skill-list prompt)', '', '| Date | Model | Suite | Skills listed | Calls | Pass | 95% interval | Tokens (fresh/cache write/cache read/out) |', '|---|---|---|---|---|---|---|---|');
    for (const r of trig) { const s = r.summary; L.push(`| ${r.date} | ${r.model} | ${r.suite} x${r.repeats} | ${r.skillsListed} | ${s.calls} | ${s.passed} (${pct(s.passed, s.calls)}) | ${wilson(s.passed, s.calls)} | ${r.tokens.fresh}/${r.tokens.cacheWrite}/${r.tokens.cacheRead}/${r.tokens.out} |`); }
    const last = trig[trig.length - 1];
    L.push('', `Per skill (latest run, ${last.date}, ${last.model}): recall = expected skill chosen; false positives = forbidden skill chosen.`, '', '| Skill | tp | fn | fp | recall | precision |', '|---|---|---|---|---|---|');
    for (const [n, o] of Object.entries(last.summary.per).sort()) L.push(`| ${n} | ${o.tp} | ${o.fn} | ${o.fp} | ${o.recall == null ? 'n/a' : pct(o.tp, o.tp + o.fn)} | ${o.precision == null ? 'n/a' : pct(o.tp, o.tp + o.fp)} |`);
    if (last.failures.length) { L.push('', 'Failures in the latest run:', ''); for (const f of last.failures.slice(0, 30)) L.push(`- "${f.prompt}" → [${f.got.join(', ')}]${f.missed.length ? ` missing ${f.missed.join(', ')}` : ''}${f.forbidden.length ? ` forbidden ${f.forbidden.join(', ')}` : ''}`); }
    L.push('');
  }
  if (scen.length) {
    L.push('## Task scenarios (graded by deterministic checks)', '');
    for (const r of scen) {
      L.push(`### ${r.date}, ${r.model}, ${r.runsPerCell} run(s) per scenario and arm, cap $${r.budgetPerRunUsd}/run`, '', '| Scenario | Arm | Runs | Passed all graders | Mean cost | Mean turns |', '|---|---|---|---|---|---|');
      const cells = {};
      for (const x of r.runs) { const k = `${x.scenario}|${x.arm}`; (cells[k] = cells[k] || []).push(x); }
      for (const [k, xs] of Object.entries(cells).sort()) { const [s, a] = k.split('|'); const ok = xs.filter((x) => x.pass).length; L.push(`| ${s} | ${a} | ${xs.length} | ${ok}/${xs.length} (${pct(ok, xs.length)}) | $${(xs.reduce((n, x) => n + x.cost, 0) / xs.length).toFixed(3)} | ${(xs.reduce((n, x) => n + x.turns, 0) / xs.length).toFixed(1)} |`); }
      const arms = [...new Set(r.runs.map((x) => x.arm))].sort();
      if (arms.length > 1) {
        L.push('', '| Arm | Runs | Passed all graders | Mean cost | Cost per passing run | Mean turns | Mean seconds |', '|---|---|---|---|---|---|---|');
        for (const a of arms) {
          const xs = r.runs.filter((x) => x.arm === a); const ok = xs.filter((x) => x.pass).length; const total = xs.reduce((n, x) => n + x.cost, 0);
          const secs = xs.filter((x) => typeof x.seconds === 'number');
          L.push(`| ${a} | ${xs.length} | ${ok}/${xs.length} (${pct(ok, xs.length)}) | $${(total / xs.length).toFixed(3)} | ${ok ? '$' + (total / ok).toFixed(3) : 'n/a (no passing run)'} | ${(xs.reduce((n, x) => n + x.turns, 0) / xs.length).toFixed(1)} | ${secs.length ? (secs.reduce((n, x) => n + x.seconds, 0) / secs.length).toFixed(1) : 'not recorded'} |`);
        }
        // Credit Reduction (%) = (baseline cost - arm cost) / baseline cost x 100, on cost per passing run so a cheap failure never counts as a saving.
        // Only measured costs from the recorded runs; token counts and cached tokens are not recorded by the scenario runner (turns and seconds are).
        if (arms.includes('baseline')) {
          const cpp = (arm) => { const xs = r.runs.filter((x) => x.arm === arm); const ok = xs.filter((x) => x.pass).length; return ok ? xs.reduce((n, x) => n + x.cost, 0) / ok : null; };
          const rate = (arm) => { const xs = r.runs.filter((x) => x.arm === arm); return xs.filter((x) => x.pass).length / xs.length; };
          const base = cpp('baseline');
          L.push('', '| Arm | Success rate vs baseline | Credit reduction vs baseline (cost per passing run) |', '|---|---|---|');
          for (const a of arms.filter((x) => x !== 'baseline')) { const c = cpp(a); L.push(`| ${a} | ${(rate(a) * 100).toFixed(0)}% vs ${(rate('baseline') * 100).toFixed(0)}% | ${base && c ? ((base - c) / base * 100).toFixed(1) + '% (negative = costs more)' : 'n/a (an arm has no passing run)'} |`); }
        }
      }
      const byCat = {};
      for (const x of r.runs) for (const g of x.graders) { const k = `${g.category}|${x.arm}`; byCat[k] = byCat[k] || [0, 0]; byCat[k][1]++; if (g.pass) byCat[k][0]++; }
      L.push('', '| Category | Arm | Graders passed |', '|---|---|---|');
      for (const [k, [p, t]] of Object.entries(byCat).sort()) { const [c, a] = k.split('|'); L.push(`| ${c} | ${a} | ${p}/${t} (${pct(p, t)}) |`); }
      L.push('', `With ${r.runsPerCell} run(s) per cell, small differences between arms are noise; a skill earns the label "evaluated" only with repeated runs recorded here.`, '');
    }
  }
  return L.join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const a = process.argv.slice(2);
  const opt = (n, d) => { const i = a.indexOf(n); return i >= 0 && a[i + 1] ? a[i + 1] : d; };
  const dir = opt('--results', path.join(HERE, 'results'));
  const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort() : [];
  const md = buildReport(files.map((f) => JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'))));
  const out = opt('--out', path.join(HERE, 'REPORT.md'));
  fs.writeFileSync(out, md + '\n');
  console.log(`wrote ${out} from ${files.length} result file(s)`);
}
